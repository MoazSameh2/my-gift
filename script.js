const song = document.getElementById("song");
const playBtn = document.getElementById("play-btn");
const disc = document.getElementById("disc");
const seek = document.getElementById("seek");
const timeEl = document.getElementById("time");
const durationEl = document.getElementById("duration");
let seeking = false;

function setFill() {
  seek.style.setProperty("--fill", seek.value + "%");
}

function togglePlay() {
  if (song.paused) {
    song.play().then(function () {
      playBtn.textContent = "⏸";
      disc.classList.add("spinning");
    }).catch(function () {
      timeEl.textContent = "❌";
    });
  } else {
    song.pause();
    playBtn.textContent = "▶";
    disc.classList.remove("spinning");
  }
}

song.addEventListener("loadedmetadata", function () {
  if (isFinite(song.duration)) {
    durationEl.textContent = formatTime(song.duration);
  }
});

song.addEventListener("durationchange", function () {
  if (isFinite(song.duration)) {
    durationEl.textContent = formatTime(song.duration);
  }
});

song.addEventListener("timeupdate", function () {
  if (!isFinite(song.duration) || seeking) {
    timeEl.textContent = formatTime(song.currentTime);
    return;
  }
  seek.value = (song.currentTime / song.duration) * 100;
  setFill();
  timeEl.textContent = formatTime(song.currentTime);
});

seek.addEventListener("input", function () {
  seeking = true;
  setFill();
  if (song.duration) {
    timeEl.textContent = formatTime((seek.value / 100) * song.duration);
  }
});

seek.addEventListener("change", function () {
  if (song.duration) {
    song.currentTime = (seek.value / 100) * song.duration;
  }
  seeking = false;
});

song.addEventListener("ended", function () {
  playBtn.textContent = "▶";
  disc.classList.remove("spinning");
  seek.value = 0;
  setFill();
  timeEl.textContent = "0:00";
});

