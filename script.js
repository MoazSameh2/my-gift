const startDate = new Date(2014, 4, 3);
const loveConfessionDate = "3/3/2025";

document.getElementById("start-date-display").textContent =
  String(startDate.getDate()).padStart(2, "0") + "-" +
  String(startDate.getMonth() + 1).padStart(2, "0") + "-" +
  startDate.getFullYear();

document.getElementById("love-date-display").textContent = loveConfessionDate;

function updateCounter() {
  const now = new Date();

  let years = now.getFullYear() - startDate.getFullYear();
  let months = now.getMonth() - startDate.getMonth();
  let days = now.getDate() - startDate.getDate();

  if (days < 0) {
    months--;
    const prevMonth = new Date(now.getFullYear(), now.getMonth(), 0);
    days += prevMonth.getDate();
  }

  if (months < 0) {
    years--;
    months += 12;
  }

  if (years < 0) { years = 0; months = 0; days = 0; }

  document.getElementById("c-years").textContent = years;
  document.getElementById("c-months").textContent = months;
  document.getElementById("c-days").textContent = days;
  document.getElementById("c-hours").textContent = now.getHours();
  document.getElementById("c-minutes").textContent = now.getMinutes();
  document.getElementById("c-seconds").textContent = now.getSeconds();
}

updateCounter();
setInterval(updateCounter, 1000);